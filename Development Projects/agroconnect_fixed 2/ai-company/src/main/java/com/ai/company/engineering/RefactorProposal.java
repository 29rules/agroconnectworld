package com.ai.company.engineering;

public class RefactorProposal {
    private String issue;
    private String proposedRefactoring;
    private String expectedBenefits;
    private String riskLevel;
    private String estimatedEffort;
    
    // Getters and Setters
    public String getIssue() { return issue; }
    public void setIssue(String issue) { this.issue = issue; }
    
    public String getProposedRefactoring() { return proposedRefactoring; }
    public void setProposedRefactoring(String proposedRefactoring) { this.proposedRefactoring = proposedRefactoring; }
    
    public String getExpectedBenefits() { return expectedBenefits; }
    public void setExpectedBenefits(String expectedBenefits) { this.expectedBenefits = expectedBenefits; }
    
    public String getRiskLevel() { return riskLevel; }
    public void setRiskLevel(String riskLevel) { this.riskLevel = riskLevel; }
    
    public String getEstimatedEffort() { return estimatedEffort; }
    public void setEstimatedEffort(String estimatedEffort) { this.estimatedEffort = estimatedEffort; }
}



